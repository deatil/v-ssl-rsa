fn test_make_privkey_pem() {
	pubkey, prikey := generate_key(2048)!

	defer {
		prikey.free()
		pubkey.free()
	}

	prikey_pem := make_privkey_pem(prikey)!
	assert prikey_pem.len > 0

	pubkey_pem := make_pubkey_pem(pubkey)!
	assert pubkey_pem.len > 0
}

